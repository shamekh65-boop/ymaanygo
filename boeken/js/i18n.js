function setLang(l){
  localStorage.setItem(LS.lang, l);
  applyLang();
}

function cycleLang(){
  const l = getLang();
  setLang(l === 'nl' ? 'en' : (l === 'en' ? 'ar' : 'nl'));
}

function setTheme(val){
  localStorage.setItem(LS.theme, val);
  applyTheme();
}

function setActiveRadio(id, on){
  const el = document.getElementById(id);
  if(!el) return;
  el.classList.toggle('active', !!on);
}

function applyTheme(){
  const t = getTheme();
  const prefersDark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  const dark = (t === 'dark') || (t === 'auto' && prefersDark);

  if(dark){
    document.body.classList.add('dark');
    document.documentElement.style.setProperty('--bg', '#0f1111');
    document.documentElement.style.setProperty('--card', '#151818');
    document.documentElement.style.setProperty('--text', '#f2f4f4');
    document.documentElement.style.setProperty('--muted', 'rgba(255,255,255,.62)');
    document.documentElement.style.setProperty('--border', 'rgba(255,255,255,.10)');
    document.documentElement.style.setProperty('--shadow', '0 16px 40px rgba(0,0,0,.40)');
  }else{
    document.body.classList.remove('dark');
    document.documentElement.style.setProperty('--bg', '#f6f6f6');
    document.documentElement.style.setProperty('--card', '#ffffff');
    document.documentElement.style.setProperty('--text', '#111');
    document.documentElement.style.setProperty('--muted', 'rgba(0,0,0,.60)');
    document.documentElement.style.setProperty('--border', 'rgba(0,0,0,.10)');
    document.documentElement.style.setProperty('--shadow', '0 12px 26px rgba(0,0,0,.10)');
  }

  setActiveRadio('themeLight', t === 'light');
  setActiveRadio('themeDark',  t === 'dark');
  setActiveRadio('themeAuto',  t === 'auto');
}

